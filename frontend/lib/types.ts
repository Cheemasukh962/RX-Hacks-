export type Mode = 'live' | 'demo';
export type Language = 'en' | 'es';
export type Style = 'brief' | 'detailed' | 'analogy' | 'audio' | 'visual';
export type Evidence = { document_id: string; quote: string };
export type DocumentType = 'after_visit_summary' | 'clinical_note';
export type CareDocument = { id: string; type: DocumentType; title: string; text: string };
export type Instruction = {
  id: string;
  kind: 'medication' | 'follow_up' | 'lab' | 'lifestyle' | 'warning_sign' | 'supply';
  medication_name: string | null;
  strength: string | null;
  dose: string | null;
  route: string | null;
  frequency_per_day: number | null;
  duration: string | null;
  action: 'start' | 'continue' | 'stop' | 'avoid' | 'change' | null;
  refills: number | null;
  quantity: number | string | null;
  due: string | null;
  evidence: Evidence;
};
export type Conflict = {
  id: string;
  type: 'dose_mismatch' | 'frequency_mismatch' | 'action_mismatch' | 'date_mismatch' | 'duration_mismatch';
  instruction_ids: string[];
  level: 'confirmed_conflict' | 'potential_conflict' | 'insufficient_data';
  resolved: boolean;
};
export type Task = { id: string; instruction_id: string; label: string; status: 'open' | 'patient_reported_done' | 'needs_clarification' | 'unknown' };
export type CarePlan = { mode: Mode; case_id: string; synthetic: boolean; documents: CareDocument[]; instructions: Instruction[]; conflicts: Conflict[]; tasks: Task[] };
export type PatientProfile = {
  mode: Mode;
  profile_id: string;
  language: Language;
  detail: 'brief' | 'detailed';
  modes: ('read' | 'listen' | 'visual')[];
  context_opt_in: string;
  term_scores: Record<string, number>;
  style_bandit: Record<Style, [number, number]>;
  teach_back_history: unknown[];
  concerns: string[];
};
export type DemoCase = { case_id: string; title: string; description: string; mode?: Mode };
export type CaseInput = { demo_case_id: string } | { documents: { text: string; type_hint?: DocumentType }[] };
export type Context = { case_id: string; profile_id: string };
export type ExplainResult = { mode: Mode; text: string; style: Style; why_this_style: string; defined_terms: (string | { term: string; definition: string })[]; citations: Evidence[]; fact_check: { passed: boolean; unsupported: string[] } };
export type AskResult = { mode: Mode; answer: string; citations: Evidence[]; in_documents: boolean; urgent: boolean };
export type SlotValue = boolean | null | 'documents_disagree';
export type TeachbackResult = { mode: Mode; labels: string[]; confidence: number; slot_check: { dose: SlotValue; frequency: SlotValue; duration: SlotValue }; source_conflict: boolean; feedback_text: string; pathway: 'ml' | 'rules' | 'both' };
export type BarrierResult = { mode: Mode; labels: string[]; confirm_prompt: string; urgent: boolean; support_text: string; example_id: string };
export type FeedbackInput = { profile_id: string; kind: 'thumbs' | 'term_tap' | 'style_change' | 'label_confirm' | 'label_correct'; payload: Record<string, unknown> };
export type BriefingResult = { mode: Mode; draft_en: string; draft_patient_language: string; citations: Evidence[] };
export type EvalResult = { mode: Mode; [key: string]: unknown };
export type PhotoResult = { mode: Mode; text: string; redacted_count: number; preview_png_b64: string; doc_type: DocumentType };
